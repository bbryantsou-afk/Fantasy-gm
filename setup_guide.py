"""New-user setup instructions using production sync, without test bookmarks."""
import streamlit as st

def render_setup_guide():
    st.markdown('### 📖 第一次使用 · 設定指南')
    desktop,phone=st.tabs(['手機＋電腦','純手機'])
    with desktop:
        st.markdown('**電腦同步 Yahoo，兩台裝置共用同一條私人連結。**')
        st.markdown('''
1. 電腦使用 Chrome 開啟本網站，進入「聯盟同步 → 首次安裝／同步說明」。
2. 下載擴充功能 ZIP 並解壓縮。
3. Chrome 開啟 `chrome://extensions`，開啟「開發人員模式」，按「載入未封裝項目」，選取含 `manifest.json` 的資料夾。
4. 在同一個 Chrome 登入 Yahoo Fantasy，再回網站重新整理。
5. 在「聯盟同步」選今天的美東日期，按「同步指定日期」。
6. 首次核對隊伍配對，按「確認隊伍配對並完成首次同步」，確認名單與 IL 正確。
7. 回到本設定頁，在下方「手機共用連結」按「建立手機共用連結」。
8. 將產生的私人連結傳到手機；電腦、手機都收藏並使用這條連結。
''')
        st.info('平常：電腦按同步，或開啟每 30 分鐘自動檢查（Chrome 須保持運作並登入 Yahoo）。手機開同一條共用連結，每 30 秒檢查共用資料變更。這種方式不需要手機同步書籤。')
    with phone:
        st.markdown('**手機自己同步，不需要電腦。手機瀏覽器同步仍為試用功能。**')
        st.markdown('''
1. 用手機 Safari／Chrome 進入「聯盟同步 → 手機直接同步（不需電腦）」。
2. 展開「設定正式同步書籤」，複製正式同步內容。
3. 在瀏覽器新增書籤，命名為「Fantasy GM 同步」；編輯該書籤的網址／位址，貼上正式同步內容，保留開頭的 `javascript:`。
4. 在同一瀏覽器的當前分頁登入 Yahoo Fantasy，開啟自己的籃球聯盟頁。
5. 執行「Fantasy GM 同步」書籤，保持頁面開啟，等讀取完成並自動返回 App。
6. 首次確認隊伍配對，按「確認隊伍配對並完成首次同步」，核對名單與 IL。
7. 回到本設定頁建立「手機共用連結」，收藏產生的私人連結作為日常入口。
8. 從這條私人連結回到「聯盟同步」，重新複製正式同步內容並更新原書籤一次，讓之後同步回到同一份共用資料。
''')
        st.caption('Safari：從書籤清單直接點。Chrome：在 Yahoo 分頁的網址列輸入書籤名稱，選有書籤圖示的結果。必須在 Yahoo 網頁執行，不是在本 App、搜尋頁或 Yahoo App 裡執行。')
        st.info('平常：開收藏的私人連結使用功能；要更新名單時，回 Yahoo 聯盟頁點同步書籤。這個流程不是背景自動同步。')
    st.caption('兩種方式都以「網站已套用」及名單核對正確為準。共用連結沒有到期限制，可手動停用；持有者可查看與修改資料，請勿公開。雲端重部署仍可能清除暫存資料，請定期下載備份。')

    st.caption('同一個瀏覽器會自動保存名單與紀錄，重新整理可還原。清除網站資料、無痕模式或換瀏覽器不會保留這份本機備份。電腦關閉後，手機仍可使用最後資料；要取得新的 Yahoo 名單，需在手機執行同步書籤。')
